using System.Net;
using System.Net.Http.Json;
using System.Text.Json;
using LocalAIAgentAPI.Infrastructure;

namespace LocalAIAgentAPI.Tests;

public sealed class ApiTests(ApiFactory factory) : IClassFixture<ApiFactory>
{
    private readonly HttpClient _client = factory.CreateClient();

    [Theory]
    [InlineData("cat.jpg", "cat")]
    [InlineData("dog.jpeg", "retriever")]
    public async Task Classifies_sample_images(string sample, string expected)
    {
        var response = await _client.PostAsync("/api/ai", Samples.Form(("model", "imageclassifier")).WithFile(sample));

        response.EnsureSuccessStatusCode();
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.Contains(expected, json.GetProperty("label").GetString(), StringComparison.OrdinalIgnoreCase);

        var top = json.GetProperty("top").EnumerateArray().Select(p => p.GetProperty("confidence").GetSingle()).ToList();
        Assert.Equal(5, top.Count);
        Assert.Equal(top.OrderByDescending(c => c), top);
        Assert.All(top, c => Assert.InRange(c, 0f, 1f));
    }

    [Fact]
    public async Task Classification_labels_have_no_index_prefix()
    {
        var response = await _client.PostAsync("/api/ai", Samples.Form(("model", "imageclassifier")).WithFile("cat.jpg"));
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();

        Assert.DoesNotMatch(@"^\s*\d", json.GetProperty("label").GetString()!);
    }

    [Fact]
    public async Task Text_output_format_returns_plain_text()
    {
        var response = await _client.PostAsync("/api/ai?outputFormat=text", Samples.Form(("model", "imageclassifier")).WithFile("cat.jpg"));

        response.EnsureSuccessStatusCode();
        Assert.Equal("text/plain", response.Content.Headers.ContentType?.MediaType);
        Assert.StartsWith("1. ", await response.Content.ReadAsStringAsync());
    }

    [Theory]
    [InlineData("/api/ai", true)]
    [InlineData("/api/ai/ocr", false)]
    [InlineData("/api/ai/describe-image", false)]
    public async Task Non_image_upload_is_a_400_without_internal_details(string path, bool needsModel)
    {
        var form = needsModel ? Samples.Form(("model", "imageclassifier")) : Samples.Form();
        form.WithBytes("definitely not an image"u8.ToArray(), "notes.txt");

        var response = await _client.PostAsync(path, form);

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
        Assert.Equal("application/problem+json", response.Content.Headers.ContentType?.MediaType);
        var body = await response.Content.ReadAsStringAsync();
        Assert.DoesNotContain("stackTrace", body, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain(" at ", body);
    }

    [Fact]
    public async Task Batch_classify_reports_bad_files_individually()
    {
        var form = Samples.Form().WithFile("cat.jpg", "files").WithFile("dog.jpeg", "files")
            .WithBytes("nope"u8.ToArray(), "bad.txt", "files");

        var response = await _client.PostAsync("/api/ai/batch-classify", form);

        response.EnsureSuccessStatusCode();
        var items = (await response.Content.ReadFromJsonAsync<JsonElement>()).EnumerateArray().ToList();
        Assert.Equal(3, items.Count);
        Assert.Contains("cat", items[0].GetProperty("label").GetString());
        Assert.Equal(JsonValueKind.String, items[2].GetProperty("error").ValueKind);
    }

    [Fact]
    public async Task Ocr_reads_english_sample()
    {
        var response = await _client.PostAsync("/api/ai/ocr", Samples.Form().WithFile("ocr-eng.png"));

        response.EnsureSuccessStatusCode();
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.Contains("quick brown fox", json.GetProperty("text").GetString(), StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public async Task Ocr_reads_traditional_chinese_sample()
    {
        var response = await _client.PostAsync("/api/ai/ocr", Samples.Form().WithFile("ocr-chi.png"));

        response.EnsureSuccessStatusCode();
        var text = (await response.Content.ReadFromJsonAsync<JsonElement>()).GetProperty("text").GetString()!;
        Assert.Contains("這是我用來測試", text);
    }

    [Fact]
    public async Task Text_generation_uses_configured_model()
    {
        var response = await _client.PostAsync("/api/ai", Samples.Form(("model", "textgeneration"), ("prompt", "hi")));

        response.EnsureSuccessStatusCode();
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.Equal("llama2", json.GetProperty("model").GetString());
        Assert.Equal("generated by llama2", json.GetProperty("response").GetString());
    }

    [Fact]
    public async Task Ollama_outage_is_reported_as_503_with_a_hint()
    {
        var factoryWithDownOllama = new ApiFactory();
        factoryWithDownOllama.Ollama.OnGenerate = (_, _) => throw new UpstreamUnavailableException("無法連線到 Ollama");
        using var client = factoryWithDownOllama.CreateClient();

        var response = await client.PostAsync("/api/ai", Samples.Form(("model", "textgeneration"), ("prompt", "hi")));

        Assert.Equal(HttpStatusCode.ServiceUnavailable, response.StatusCode);
        Assert.Contains("Ollama", await response.Content.ReadAsStringAsync());
        await factoryWithDownOllama.DisposeAsync();
    }

    [Fact]
    public async Task Unknown_model_is_a_400()
    {
        var response = await _client.PostAsync("/api/ai", Samples.Form(("model", "gpt-9"), ("prompt", "hi")));

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    [Fact]
    public async Task Serves_front_end_and_health()
    {
        var index = await _client.GetAsync("/");
        index.EnsureSuccessStatusCode();
        Assert.Contains("<html", await index.Content.ReadAsStringAsync());

        var health = await _client.GetAsync("/health");
        health.EnsureSuccessStatusCode();
    }

    [Fact]
    public async Task Swagger_document_generates()
    {
        var response = await _client.GetAsync("/swagger/v1/swagger.json");

        response.EnsureSuccessStatusCode();
        Assert.Contains("/api/AI/describe-image", await response.Content.ReadAsStringAsync());
    }

    [Theory]
    [InlineData("https://reedlin2002.github.io", true)]
    [InlineData("https://evil.example", false)]
    public async Task Cors_only_allows_configured_origins(string origin, bool allowed)
    {
        using var request = new HttpRequestMessage(HttpMethod.Options, "/api/ai/ocr");
        request.Headers.Add("Origin", origin);
        request.Headers.Add("Access-Control-Request-Method", "POST");

        var response = await _client.SendAsync(request);

        Assert.Equal(allowed, response.Headers.Contains("Access-Control-Allow-Origin"));
    }
}
