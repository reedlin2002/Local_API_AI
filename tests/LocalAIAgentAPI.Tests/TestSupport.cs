/// <summary>Runs the real API (real ONNX model and Tesseract) with Ollama replaced by <see cref="FakeOllama"/>.</summary>
public sealed class ApiFactory : WebApplicationFactory<Program>
{
    public FakeOllama Ollama { get; } = new();

    protected override void ConfigureWebHost(IWebHostBuilder builder) =>
        builder.ConfigureTestServices(services =>
        {
            services.RemoveAll<IOllamaClient>();
            services.AddSingleton<IOllamaClient>(Ollama);
        });
}

public sealed class FakeOllama : IOllamaClient
{
    public List<(string Model, string Prompt, int Images)> GenerateCalls { get; } = [];
    public List<(string Model, List<ChatMessage> Messages, bool HadTools)> ChatCalls { get; } = [];

    /// <summary>Return a value, or throw to simulate an Ollama failure.</summary>
    public Func<string, string, string> OnGenerate { get; set; } = (model, _) => $"generated by {model}";

    public Queue<Func<ChatMessage>> ChatReplies { get; } = new();

    public Task<string> GenerateAsync(string model, string prompt, IReadOnlyList<byte[]>? images, CancellationToken cancellationToken)
    {
        GenerateCalls.Add((model, prompt, images?.Count ?? 0));
        return Task.FromResult(OnGenerate(model, prompt));
    }

    public Task<ChatMessage> ChatAsync(string model, IReadOnlyList<ChatMessage> messages, IReadOnlyList<ToolDefinition>? tools, CancellationToken cancellationToken)
    {
        ChatCalls.Add((model, messages.ToList(), tools is { Count: > 0 }));
        var reply = ChatReplies.Count > 0 ? ChatReplies.Dequeue()() : new ChatMessage("assistant", "default answer");
        return Task.FromResult(reply);
    }
}

public sealed class FakeClassifier : IImageClassifier
{
    public int Calls { get; private set; }

    public Task<ClassificationResult> ClassifyAsync(byte[] image, int topK, CancellationToken cancellationToken)
    {
        Calls++;
        var top = new List<Prediction> { new("tabby, tabby cat", 0.8f), new("tiger cat", 0.1f) };
        return Task.FromResult(new ClassificationResult(top[0].Label, top[0].Confidence, top));
    }
}

public sealed class FakeOcr : IOcrService
{
    public int Calls { get; private set; }

    public Task<string> RecognizeTextAsync(byte[] image, CancellationToken cancellationToken)
    {
        Calls++;
        return Task.FromResult("HELLO FROM OCR");
    }
}

public static class Samples
{
    public static byte[] Read(string name) => File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "samples", name));

    public static MultipartFormDataContent Form(params (string Name, string Value)[] fields)
    {
        var form = new MultipartFormDataContent();
        foreach (var (name, value) in fields)
            form.Add(new StringContent(value), name);
        return form;
    }

    public static MultipartFormDataContent WithFile(this MultipartFormDataContent form, string sampleName, string field = "file") =>
        form.WithBytes(Read(sampleName), sampleName, field);

    public static MultipartFormDataContent WithBytes(this MultipartFormDataContent form, byte[] bytes, string fileName, string field = "file")
    {
        var content = new ByteArrayContent(bytes);
        content.Headers.ContentType = new MediaTypeHeaderValue("application/octet-stream");
        form.Add(content, field, fileName);
        return form;
    }

    public static Microsoft.Extensions.Options.IOptions<OllamaOptions> OllamaOptions(Action<OllamaOptions>? configure = null)
    {
        var options = new OllamaOptions();
        configure?.Invoke(options);
        return Microsoft.Extensions.Options.Options.Create(options);
    }
}
